function M_rec = InverseOKA_Vectorized(T_in, params, verbose)
    %INVERSEOKA_VECTORIZED Vectorized Inverse Quaternion OKA (Adjoint Operator).
    %   M_rec = INVERSEOKA_VECTORIZED(T_in, params) reconstructs the original 
    %   tensor from the high-order representation generated by OKA_VECTORIZED.
    %   It implicitly performs local smooth filtering by averaging pixels 
    %   in overlapping receptive fields.
    %
    %   Inputs:
    %       T_in   - The high-order quaternion tensor (output of OKA_VECTORIZED).
    %       params - The parameter structure returned by OKA_VECTORIZED.
    %       verbose- (Optional) Logical flag to print execution details. Default is false.
    %
    %   Outputs:
    %       M_rec  - The reconstructed third-order quaternion tensor.

    if nargin < 3
        verbose = false;
    end
    
    if ~isstruct(params) || ~isfield(params, 'steps') || ~isfield(params, 'history')
        error('InverseOKA:InvalidParams', 'Invalid params structure. Use the output from OKA_Vectorized.');
    end

    current_tensor = T_in;
    steps = params.steps;
    
    if verbose && steps > 0
        fprintf('Starting vectorized Inverse OKA (%d steps)...\n', steps);
    end
    
    for s = steps:-1:1
        p = params.history(s);
        H_dim_idx = p.dim_idx(1);
        W_dim_idx = p.dim_idx(2);
        
        sz = size(current_tensor);
        if length(sz) < 2
            % Extreme edge case protection
            M_rec = current_tensor;
            return;
        end
        
        % The first dimension contains the 4 stacked blocks
        remaining_sz = sz(2:end);
        
        idx_base = repmat({':'}, 1, ndims(current_tensor));
        
        idx = idx_base; idx{1} = 1; B1 = reshape(current_tensor(idx{:}), remaining_sz);
        idx = idx_base; idx{1} = 2; B2 = reshape(current_tensor(idx{:}), remaining_sz);
        idx = idx_base; idx{1} = 3; B3 = reshape(current_tensor(idx{:}), remaining_sz);
        idx = idx_base; idx{1} = 4; B4 = reshape(current_tensor(idx{:}), remaining_sz);
        
        target_sz = remaining_sz;
        target_sz(H_dim_idx) = p.H;
        target_sz(W_dim_idx) = p.W;
        
        Accumulator = zeros(target_sz);
        Counter = zeros(target_sz);
        
        indices = p.indices;
        [Accumulator, Counter] = add_block(Accumulator, Counter, B1, H_dim_idx, W_dim_idx, indices(1,:));
        [Accumulator, Counter] = add_block(Accumulator, Counter, B2, H_dim_idx, W_dim_idx, indices(2,:));
        [Accumulator, Counter] = add_block(Accumulator, Counter, B3, H_dim_idx, W_dim_idx, indices(3,:));
        [Accumulator, Counter] = add_block(Accumulator, Counter, B4, H_dim_idx, W_dim_idx, indices(4,:));
        
        % Avoid division by zero
        Counter(Counter == 0) = 1; 
        current_tensor = Accumulator ./ Counter;
        
        if verbose
            fprintf('  Inverse Step %d completed, size: %s\n', s, mat2str(size(current_tensor)));
        end
    end
    
    M_rec = current_tensor;
end

function [Acc, Cnt] = add_block(Acc, Cnt, Block, h_dim, w_dim, idx_vec)
    %ADD_BLOCK Accumulates a block into the target tensor based on indices.
    r_s = idx_vec(1); r_e = idx_vec(2);
    c_s = idx_vec(3); c_e = idx_vec(4);
    
    idx_base = repmat({':'}, 1, ndims(Acc));
    idx_base{h_dim} = r_s:r_e;
    idx_base{w_dim} = c_s:c_e;
    
    Acc(idx_base{:}) = Acc(idx_base{:}) + Block;
    Cnt(idx_base{:}) = Cnt(idx_base{:}) + 1;
end